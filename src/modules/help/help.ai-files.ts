import {validateHelpOfficeFile,type HelpOfficeFile} from './help.office-contract';
import {validateHelpHtmlFiles,type HelpHtmlFile,type HelpHtmlArtifact} from './help.html';
import {helpHtmlAttachmentGeometry} from './help.html-geometry';
import { randomUUID, createHash } from 'node:crypto';
import { DeleteObjectCommand, PutObjectCommand } from '@aws-sdk/client-s3';
import { ensureHelpBucket, helpBucket, helpS3, helpStorageRequest } from './help.storage';
import { validateHelpAIFiles, type HelpAIFile } from './help.ai-file-contract';

export type PreparedHelpAIFile = {
  id: string; name: string; mimeType: string; kind: 'FILE'; size: number;
  objectKey: string; sha256: string; position: number; width?:number|null; height?:number;
};
const UPLOAD_TIMEOUT_MS = 10000;
const CLEANUP_TIMEOUT_MS = 5000;

function bounded<T>(work: Promise<T>, signal: AbortSignal): Promise<T> {
  return new Promise((resolve, reject) => {
    const abort = () => { cleanup(); reject(signal.reason); };
    const cleanup = () => signal.removeEventListener('abort', abort);
    work.then(value => { cleanup(); resolve(value); }, error => { cleanup(); reject(error); });
    if (signal.aborted) abort(); else signal.addEventListener('abort', abort, { once: true });
  });
}

/** Each attempt owns fresh keys, so cleanup can never erase a winner's files. */
export async function cleanupHelpAIFiles(files: PreparedHelpAIFile[]): Promise<void> {
  await Promise.all(files.map(async file => {
    const deadline = new AbortController();
    const timer = setTimeout(() => deadline.abort(), CLEANUP_TIMEOUT_MS); timer.unref();
    try {
      await bounded(helpStorageRequest(() => helpS3.send(new DeleteObjectCommand({ Bucket: helpBucket, Key: file.objectKey }), { abortSignal: deadline.signal })), deadline.signal);
    } catch { console.warn('[help-ai-files] cleanup deferred', { code: 'HELP_AI_FILE_CLEANUP' }); }
    finally { clearTimeout(timer); }
  }));
}

/** Upload outside SQL; attachment rows and access become visible only in the final transaction. */
export async function prepareHelpAIFiles(scope: { ticketId: number; runId: string }, files: HelpAIFile[], signal: AbortSignal): Promise<PreparedHelpAIFile[]> {
  const validated = validateHelpAIFiles(files);
  if (!validated.length) return [];
  if (!Number.isSafeInteger(scope.ticketId) || scope.ticketId < 1 || !/^[a-z0-9_-]{1,100}$/i.test(scope.runId)) throw new Error('HELP_AI_INVALID_FILE_SCOPE');
  signal.throwIfAborted();
  const deadline = new AbortController(), timer = setTimeout(() => deadline.abort(), UPLOAD_TIMEOUT_MS); timer.unref();
  const combined = AbortSignal.any([signal, deadline.signal]);
  const prepared: PreparedHelpAIFile[] = [];
  try {
    await bounded(ensureHelpBucket(), combined);
    for (const [position, file] of validated.entries()) {
      combined.throwIfAborted();
      const id = randomUUID(), extension = file.name.split('.').slice(-1)[0].toLowerCase();
      const descriptor: PreparedHelpAIFile = { id, name: file.name, mimeType: file.mimeType, kind: 'FILE', position,
        size: file.bytes.length, sha256: createHash('sha256').update(file.bytes).digest('hex'),
        objectKey: `help/ai/${scope.ticketId}/${scope.runId}/${id}.${extension}` };
      prepared.push(descriptor);
      const upload = helpStorageRequest(() => helpS3.send(new PutObjectCommand({ Bucket: helpBucket,
        Key: descriptor.objectKey, Body: file.bytes, ContentType: `${file.mimeType}; charset=utf-8`,
        ContentLength: file.bytes.length, CacheControl: 'private, no-store' }), { abortSignal: combined }));
      // A broken transport may complete a PUT after our timeout/delete. Delete
      // that attempt's unique object once more when the late PUT finally settles.
      void upload.then(() => { if (combined.aborted) void cleanupHelpAIFiles([descriptor]); }, () => {});
      await bounded(upload, combined);
    }
    return prepared;
  } catch (error) { await cleanupHelpAIFiles(prepared); throw error; }
  finally { clearTimeout(timer); }
}

/** Office binaries originate only in server renderers, never arbitrary model-generated byte strings. */
export async function prepareHelpOfficeFiles(scope:{ticketId:number;runId:string},files:HelpOfficeFile[],signal:AbortSignal,positionOffset=0):Promise<PreparedHelpAIFile[]> {
 return prepareHelpRenderedFiles(scope,files.map(validateHelpOfficeFile),signal,positionOffset);
}
export async function prepareHelpHtmlFiles(scope:{ticketId:number;runId:string},files:HelpHtmlFile[],signal:AbortSignal,positionOffset=0):Promise<PreparedHelpAIFile[]> {
 return prepareHelpRenderedFiles(scope,validateHelpHtmlFiles(files),signal,positionOffset);
}
